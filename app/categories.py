# 대분류만 알고 세부분류를 못 잡았을 때 쓰는 대체 세부분류
_MAJOR_FALLBACK_DETAIL = {
    "중식": "짬뽕",
    "분식": "분식",
    "치킨": "치킨",
    "뷔페": "뷔페",
    "구내식당": "구내식당",
}

_SPLIT = re.compile(r"[>|/,]")


def _norm(text: str) -> str:
    return re.sub(r"\s+", "", (text or "").lower())


def classify_major(raw_category: str, name: str = "") -> str:
    """대분류(한식/중식/일식/...)를 고른다."""
    segments = [s for s in _SPLIT.split(raw_category or "") if s.strip()]
    # '음식점' 같은 최상위 세그먼트는 건너뛰고 뒤쪽부터 본다.
    haystacks = [_norm(s) for s in reversed(segments)] + [_norm(name)]
    for hay in haystacks:
        if not hay or hay in {"음식점", "맛집"}:
            continue
        for major, keys in _MAJOR_ALIASES.items():
            if any(_norm(k) in hay for k in keys):
                return major
    return UNKNOWN


def classify_detail(raw_category: str, name: str = "") -> str:
    """세부분류를 고른다. 카테고리 문자열을 상호명보다 우선한다."""
    cat = _norm(raw_category)
    nm = _norm(name)
    for detail, keys in _DETAIL_RULES:
        if any(_norm(k) in cat for k in keys):
            return detail
    for detail, keys in _DETAIL_RULES:
        if any(_norm(k) in nm for k in keys):
            return detail
    return ""


def classify(raw_category: str, name: str = "") -> tuple[str, str]:
    """(대분류, 세부분류)를 돌려준다. 세부분류를 못 잡으면 대분류로 대체."""
    major = classify_major(raw_category, name)
    detail = classify_detail(raw_category, name)
    if not detail:
        detail = _MAJOR_FALLBACK_DETAIL.get(major, major)
    return major, detail


def dedupe_key(major: str, detail: str) -> str:
    """추천 3개가 서로 겹치지 않게 할 때 쓰는 키."""
    return (detail or major or UNKNOWN).strip()


